export const STORE_LOCALES: Record<StorePlatform, LocaleOption[]> = {
  appstore: APPSTORE_LOCALES,
  playstore: PLAYSTORE_LOCALES,
};

/** Codes valides pour un store donné (validation côté serveur). */
export function isValidLocale(store: StorePlatform, code: string): boolean {
  return STORE_LOCALES[store].some((l) => l.value === code);
}
